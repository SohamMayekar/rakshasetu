DEVANAGARI = [("{v} में {n} लोग छत पर फँसे हैं, पानी बढ़ रहा है", ["trapped_on_roof", "water_rising"]),
              ("{v} में {n} लोग फँसे हैं, दवाई चाहिए", ["trapped_inside", "medicine"]),
              ("{v} में घर में पानी घुस गया है, {n} लोग हैं, एक बुज़ुर्ग हैं", ["water_entering", "elderly"])]
NEED_TYPES = {"medicine", "food", "drinking_water", "baby_supplies", "medical_urgent"}
VULN_TYPES = {"elderly", "infant", "child", "pregnant", "disabled"}
RELATIONS = ["family", "family", "neighbour", "self", "volunteer", "forwarder"]


def offset(lat, lon, rng, max_m=800):
    """A household somewhere near the village point (not on it)."""
    import math
    d = rng.uniform(150, max_m)
    a = rng.uniform(0, 2 * math.pi)
    return round(lat + d * math.cos(a) / 111_000, 6), round(lon + d * math.sin(a) / (111_000 * math.cos(math.radians(lat))), 6)


def make_case(i, rng):
    name, name_hi, lat, lon, district = rng.choice(VILLAGES)
    n = rng.choice([2, 3, 4, 4, 5, 5, 6, 6, 7, 8, 9, 12])
    script = rng.choice(["hinglish", "hinglish", "hinglish", "english", "devanagari"])
    if script == "devanagari":
        template, kinds = rng.choice(DEVANAGARI)
        text = template.format(v=name_hi, n=n)
    else:
        bank = BANK[script]
        situation = rng.choice(["trapped_on_roof", "trapped_on_roof", "trapped_inside", "cut_off"])
        kinds = [situation]
        kinds += rng.sample(["water_entering", "water_rising"], k=rng.choice([0, 1, 1]))
        kinds += rng.sample(["elderly", "infant", "child", "pregnant", "disabled"], k=rng.choice([0, 0, 1]))
        kinds += rng.sample(["medicine", "food", "drinking_water", "baby_supplies"], k=rng.choice([0, 1, 1]))
        if rng.random() < 0.08:
            kinds.append("medical_urgent")
        parts = [rng.choice(bank["lead"]).format(v=name)] + [rng.choice(bank[k]).format(n=n) for k in kinds]
        tail = rng.choice(bank["tail"])
        text = " ".join([parts[0], ", ".join(parts[1:])]) + (f". {tail[0].upper()}{tail[1:]}" if tail else "")
    hlat, hlon = offset(lat, lon, rng)
    return {
        "key": f"br-{i:03d}",
        "district": district,
        "minutes_ago": 0,  # filled below
        "channel": rng.choice(["web_form", "web_form", "web_form", "partner", "spreadsheet"]),
        "relation": rng.choice(RELATIONS),
        "phone": f"+91 98765 {20000 + i:05d}",
        "text": text,
        "status": rng.choice(["reported", "reported", "checked"]),
        "truth": {
            "village": name, "village_point": [lat, lon], "household": [hlat, hlon], "people_count": n,
            "hazards": sorted(k for k in kinds if k not in NEED_TYPES | VULN_TYPES),
            "needs": sorted(k for k in kinds if k in NEED_TYPES),
            "vulnerable": sorted(k for k in kinds if k in VULN_TYPES),
        },
    }


def main():
    rng = random.Random(2026)
    cases = [make_case(i, rng) for i in range(1, 47)]
    # Two honesty cases the PRD requires on screen (F-L4 "seeded honesty"):
    cases.append({"key": "br-low", "district": "Gopalganj", "minutes_ago": 0, "channel": "web_form", "relation": "family",
                  "phone": "+91 98765 29001", "status": "reported",
                  "text": "Phulwaria mein hamare rishtedaar fase hain, 4 log, khana nahi hai",
                  "truth": {"village": "Phulwaria", "village_point": [26.45924, 84.250717], "household": None, "people_count": 4, "hazards": ["trapped_inside"],
                            "needs": ["food"], "vulnerable": [], "note": "village only: expect a Low 1.5 km circle"}})
    cases.append({"key": "br-noloc", "district": "Gopalganj", "minutes_ago": 0, "channel": "web_form", "relation": "family",
                  "phone": "+91 98765 29002", "status": "reported",
                  "text": "Hum log fase hain, 3 log hain, jaldi aaiye",
                  "truth": {"village": None, "village_point": None, "household": None, "people_count": 3, "hazards": ["trapped_inside"],
                            "needs": [], "vulnerable": [], "note": "no location: expect a Needs location row (P2, so a reset starts with no broken P1 promise)"}})
    # Spread report times over the last ten hours, oldest first (timestamps are relative to the seed moment).
    ages = sorted((rng.randint(8, 600) for _ in cases), reverse=True)
    for c, age in zip(cases, ages):
        c["minutes_ago"] = age
    header = ("# GENERATED by scripts/gen_seed_cases.py — do not edit by hand.\n"
              "# Synthetic household reports at real OSM places (Gopalganj and Muzaffarpur, Bihar).\n"
              "# All names and phone numbers are synthetic and never dialled. `truth` is what the text says.\n")
    OUT.write_text(header + yaml.safe_dump({"cases": cases}, allow_unicode=True, sort_keys=False, width=140))
    print(f"wrote {len(cases)} cases to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
